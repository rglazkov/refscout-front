/**
 * Lifts the OpenAPI document out of the API specification and writes it to
 * `contract/refscout-api.yaml`.
 *
 * The specification is the original: it is where the API is designed, argued
 * about and agreed with the backend. This script exists so that the document is
 * never maintained in two places - editing the YAML by hand would put the copy
 * and the specification into a slow disagreement that nobody notices until a
 * generated type is wrong.
 *
 * It is deliberately NOT part of `npm run contract`. The specification lives
 * outside this repository, so a CI checkout does not have it, and
 * `contract/refscout-api.yaml` is committed and is what every other step reads.
 * Run this by hand when the specification changes, and commit the result:
 *
 *   npm run contract:extract && npm run contract
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const SPEC = path.join(root, "..", "refscout_api_spec.md");
const TARGET = path.join(root, "contract", "refscout-api.yaml");

let markdown;
try {
  // The specification is written on Windows and stored with CRLF endings, and
  // Node does not normalise them on read.
  const raw = readFileSync(SPEC, "utf8");
  markdown = raw.split("\r\n").join("\n");
} catch {
  console.error(`Cannot read the API specification at ${SPEC}.`);
  console.error("It lives outside this repository, so this command only runs");
  console.error("locally; CI reads the committed contract/refscout-api.yaml.");
  process.exit(1);
}

// One fenced YAML block in the specification is the OpenAPI document. Matching
// on the opening key rather than on position means that a code block added
// elsewhere in the specification cannot quietly become the contract.
const blocks = [...markdown.matchAll(/\n```yaml\n([\s\S]*?)\n```/g)]
  .map((match) => match[1])
  .filter((body) => /^openapi:\s*3\./.test(body));

if (blocks.length !== 1) {
  console.error(
    `Expected exactly one OpenAPI block in the specification, found ${blocks.length}.`,
  );
  process.exit(1);
}

const banner =
  "# Generated by scripts/extract-contract.mjs from refscout_api_spec.md.\n" +
  "# Do not edit by hand - edit the specification and re-run\n" +
  "#   npm run contract:extract && npm run contract\n" +
  "# Committed because CI has no access to the specification.\n\n";

mkdirSync(path.dirname(TARGET), { recursive: true });
writeFileSync(TARGET, banner + blocks[0] + "\n", "utf8");
console.log(
  `  contract: ${blocks[0].split("\n").length} lines -> contract/refscout-api.yaml`,
);
